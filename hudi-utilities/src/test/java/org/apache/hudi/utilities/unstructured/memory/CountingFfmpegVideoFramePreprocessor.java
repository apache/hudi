package org.apache.hudi.utilities.unstructured.memory;

import org.apache.hudi.common.config.TypedProperties;
import org.apache.hudi.common.util.collection.ClosableIterator;
import org.apache.hudi.utilities.unstructured.embedding.prep.Chunk;
import org.apache.hudi.utilities.unstructured.embedding.prep.VideoFramePreprocessor;
import org.apache.hudi.utilities.unstructured.embedding.source.BlobBytesSupplier;
import org.apache.hudi.utilities.unstructured.embedding.source.FileMeta;
import org.apache.hudi.utilities.unstructured.embedding.text.Tokenizer;

import java.io.IOException;

/** The default FFmpeg frame preprocessor, unchanged, with each decode counted by {@link VideoDecodeConcurrency} (same name, same rows). */
public class CountingFfmpegVideoFramePreprocessor extends VideoFramePreprocessor {

  @Override
  public ClosableIterator<Chunk> open(BlobBytesSupplier bytes, FileMeta file, Tokenizer tokenizer, TypedProperties props)
      throws IOException {
    return VideoDecodeConcurrency.track(super.open(bytes, file, tokenizer, props));
  }
}
