/**
 * Custom Spark-specific [[KeyGenerator]] overriding behavior handling [[TimestampType]] partition values
 */
class SqlKeyGenerator(props: TypedProperties) extends BuiltinKeyGenerator(props) {

  private lazy val partitionSchema = {
    val partitionSchema = props.getString(SqlKeyGenerator.PARTITION_SCHEMA, "")
    if (partitionSchema != null && partitionSchema.nonEmpty) {
      Some(StructType.fromDDL(partitionSchema))
    } else {
      None
    }
  }

  private lazy val keepFractionalSeconds = props.getBoolean(
    KeyGeneratorOptions.TIMESTAMP_PARTITION_FRACTIONAL_SECONDS.key,
    KeyGeneratorOptions.TIMESTAMP_PARTITION_FRACTIONAL_SECONDS.defaultValue.toBoolean)

  private lazy val autoRecordKeyGen = KeyGenUtils.isAutoGeneratedRecordKeysEnabled(props)
  private lazy val complexKeyGen = if (autoRecordKeyGen) {
    new AutoRecordGenWrapperKeyGenerator(props, new ComplexKeyGenerator(props))
  } else {
    new ComplexKeyGenerator(props)
  }
  private lazy val originalKeyGen =
    Option(props.getString(SqlKeyGenerator.ORIGINAL_KEYGEN_CLASS_NAME, null))
      .map { originalKeyGenClassName =>
        checkArgument(originalKeyGenClassName.nonEmpty)

        val convertedKeyGenClassName = HoodieSparkKeyGeneratorFactory.convertToSparkKeyGenerator(originalKeyGenClassName)

        val keyGenProps = TypedProperties.fromMap(props)
        keyGenProps.remove(SqlKeyGenerator.ORIGINAL_KEYGEN_CLASS_NAME)
        keyGenProps.put(HoodieWriteConfig.KEYGENERATOR_CLASS_NAME.key, convertedKeyGenClassName)

        val keyGenerator = KeyGenUtils.createKeyGeneratorByClassName(keyGenProps).asInstanceOf[SparkKeyGeneratorInterface]
        if (autoRecordKeyGen) {
          new AutoRecordGenWrapperKeyGenerator(keyGenProps, keyGenerator.asInstanceOf[BuiltinKeyGenerator])
        } else {
          keyGenerator
        }
      }

  override def getRecordKey(record: GenericRecord): String =
    originalKeyGen.map {
      _.getKey(record).getRecordKey
    } getOrElse {
      complexKeyGen.getRecordKey(record)
    }

  override def getRecordKey(row: Row): String =
    originalKeyGen.map {
      _.getRecordKey(row)
    } getOrElse {
      complexKeyGen.getRecordKey(row)
    }


  override def getRecordKey(internalRow: InternalRow, schema: StructType): UTF8String =
    originalKeyGen.map {
      _.getRecordKey(internalRow, schema)
    } getOrElse {
      complexKeyGen.getRecordKey(internalRow, schema)
    }

  override def getPartitionPath(record: GenericRecord): String = {
    val partitionPath = originalKeyGen.map {
      // Resolve the partition path on its own where the key generator exposes it. Going through
      // BaseKeyGenerator#getKey would also compute and validate the record key, which a MOR partial
      // update legitimately leaves unset: the merged record is materialised against
      // WRITE_PARTIAL_UPDATE_SCHEMA and so carries only the columns named in UPDATE SET. Callers
      // that want the record key validated still ask for it, via getKey or getRecordKey.
      case baseKeyGen: BaseKeyGenerator => baseKeyGen.getPartitionPath(record)
      // SparkKeyGeneratorInterface exposes no Avro-facing accessor beyond getKey, so a generator
      // that is not a BaseKeyGenerator retains the previous behaviour.
      case keyGen => keyGen.getKey(record).getPartitionPath
    } getOrElse {
      complexKeyGen.getPartitionPath(record)
    }

    convertPartitionPathToSqlType(partitionPath, rowType = false, SqlKeyGenerator.avroTimestampMicros(record, _))
  }

  override def getPartitionPath(row: Row): String = {
    val partitionPath = originalKeyGen.map {
      _.getPartitionPath(row)
    } getOrElse {
      complexKeyGen.getPartitionPath(row)
    }

    convertPartitionPathToSqlType(partitionPath, rowType = true, SqlKeyGenerator.rowTimestampMicros(row, _))
  }

  override def getPartitionPath(internalRow: InternalRow, schema: StructType): UTF8String = {
    val partitionPath = originalKeyGen.map {
      _.getPartitionPath(internalRow, schema)
    } getOrElse {
      complexKeyGen.getPartitionPath(internalRow, schema)
    }

    UTF8String.fromString(convertPartitionPathToSqlType(partitionPath.toString, rowType = true,
      SqlKeyGenerator.internalRowTimestampMicros(internalRow, schema, _)))
  }

  override def getRecordKeyFieldNames: util.List[String] = {
    originalKeyGen.map(_.getRecordKeyFieldNames)
      .getOrElse(complexKeyGen.getRecordKeyFieldNames)
  }

  override def getPartitionPathFields: util.List[String] = {
    originalKeyGen.map {
      case bkg: BaseKeyGenerator => bkg.getPartitionPathFields
      case _ =>
        Option(super.getPartitionPathFields).getOrElse(Collections.emptyList[String])
    } getOrElse {
      complexKeyGen.getPartitionPathFields
    }
  }

  // TODO clean up
  /**
   * @param exactMicros reads the value of a TIMESTAMP partition field from the record, when it can. The
   *                    partition path built by the delegate holds at most milliseconds for an
   *                    [[InternalRow]], or with consistent logical timestamps enabled.
   */
  private def convertPartitionPathToSqlType(partitionPath: String, rowType: Boolean,
                                            exactMicros: StructField => Option[Long]): String = {
    if (partitionSchema.isDefined) {
      // we can split the partitionPath here because we enable the URL_ENCODE_PARTITIONING_OPT
      // by default for sql.
      val partitionFragments = partitionPath.split(KeyGenUtils.DEFAULT_PARTITION_PATH_SEPARATOR)
      // If it is a table which is not write by spark sql before and the url encode has disabled,
      // the partition path level may not equal to the partition schema size. Just return the partitionPath
      // in this case.
      if (partitionFragments.size != partitionSchema.get.size) {
        partitionPath
      } else {
        partitionFragments.zip(partitionSchema.get.fields).map {
          case (partitionValue, partitionField) =>
            val hiveStylePrefix = s"${partitionField.name}="
            val isHiveStyle = partitionValue.startsWith(hiveStylePrefix)
            val _partitionValue = if (isHiveStyle) partitionValue.substring(hiveStylePrefix.length) else partitionValue
            if (_partitionValue == PartitionPathEncodeUtils.DEFAULT_PARTITION_PATH) {
              partitionValue
            } else if (slashSeparatedDatePartitioning) {
              partitionValue.replace('/', '-')
            } else {
              partitionField.dataType match {
                case TimestampType if keepFractionalSeconds =>
                  val micros = exactMicros(partitionField).getOrElse {
                    if (rowType || isConsistentLogicalTimestampEnabled) {
                      DateTimeUtils.fromJavaTimestamp(Timestamp.valueOf(PartitionPathEncodeUtils.unescapePathName(_partitionValue)))
                    } else {
                      _partitionValue.toLong
                    }
                  }
                  val timestampFormat = PartitionPathEncodeUtils.escapePathName(SqlKeyGenerator.formatTimestamp(micros))
                  if (isHiveStyle) s"$hiveStylePrefix$timestampFormat" else timestampFormat
                case TimestampType =>
                  val timeMs = if (rowType) { // In RowType, the partitionPathValue is the time format string, convert to millis
                    SqlKeyGenerator.sqlTimestampFormat.parseMillis(_partitionValue)
                  } else {
                    if (isConsistentLogicalTimestampEnabled) {
                      Timestamp.valueOf(_partitionValue).getTime
                    } else {
                      MILLISECONDS.convert(_partitionValue.toLong, MICROSECONDS)
                    }
                  }
                  val timestampFormat = PartitionPathEncodeUtils.escapePathName(
                    SqlKeyGenerator.timestampTimeFormat.print(timeMs))
                  if (isHiveStyle) s"$hiveStylePrefix$timestampFormat" else timestampFormat
                case _ => partitionValue
              }
            }
        }.mkString(KeyGenUtils.DEFAULT_PARTITION_PATH_SEPARATOR)
      }
    } else partitionPath
  }
}

object SqlKeyGenerator {
  val PARTITION_SCHEMA = "hoodie.sql.partition.schema"
  val ORIGINAL_KEYGEN_CLASS_NAME = "hoodie.sql.origin.keygen.class"
  private val timestampTimeFormat = DateTimeFormat.forPattern("yyyy-MM-dd HH:mm:ss")
  // Parses one to nine fractional digits, as java.sql.Timestamp#toString prints them
  private val sqlTimestampFormat = DateTimeFormat.forPattern("yyyy-MM-dd HH:mm:ss.SSSSSSSSS")
  // Spark's rendering of a timestamp cast to a string: the fraction loses its trailing zeros, and a
  // whole-second value has none
  private val fractionalTimestampFormat: DateTimeFormatter = new DateTimeFormatterBuilder()
    .appendPattern("uuuu-MM-dd HH:mm:ss")
    .appendFraction(ChronoField.NANO_OF_SECOND, 0, 6, true)
    .toFormatter

  /** Prints in the zone the whole-second format is printed in, so a whole-second value has the same path. */
  private def formatTimestamp(micros: Long): String =
    fractionalTimestampFormat.format(LocalDateTime.ofInstant(
      Instant.ofEpochSecond(Math.floorDiv(micros, 1000000L), Math.floorMod(micros, 1000000L) * 1000L),
      ZoneId.of(DateTimeZone.getDefault.getID)))

  private def avroTimestampMicros(record: GenericRecord, field: StructField): Option[Long] =
    Option(record.getSchema.getField(field.name)).flatMap { avroField =>
      val logicalType = HoodieAvroUtils.unwrapNullable(avroField.schema).getLogicalType
      (logicalType, record.get(avroField.pos)) match {
        case (_: LogicalTypes.TimestampMicros, micros: java.lang.Long) => Some(micros.longValue)
        case (_: LogicalTypes.TimestampMillis, millis: java.lang.Long) => Some(millis.longValue * 1000L)
        case (_: LogicalTypes.TimestampMicros | _: LogicalTypes.TimestampMillis, instant: Instant) => Some(DateTimeUtils.instantToMicros(instant))
        case _ => None
      }
    }

  private def rowTimestampMicros(row: Row, field: StructField): Option[Long] =
    Option(row.schema).flatMap(schema => schema.getFieldIndex(field.name)).flatMap { index =>
      row.get(index) match {
        case timestamp: Timestamp => Some(DateTimeUtils.fromJavaTimestamp(timestamp))
        case instant: Instant => Some(DateTimeUtils.instantToMicros(instant))
        case _ => None
      }
    }

  private def internalRowTimestampMicros(row: InternalRow, schema: StructType, field: StructField): Option[Long] =
    schema.getFieldIndex(field.name)
      .filter(index => schema(index).dataType == TimestampType && !row.isNullAt(index))
      .map(row.getLong)
}
